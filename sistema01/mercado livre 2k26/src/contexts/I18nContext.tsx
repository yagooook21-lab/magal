interface I18nContextType {
  language: Language;
  currency: Currency;
  country: Country;
  setLanguage: (lang: Language) => void;
  setCurrency: (curr: Currency) => void;
  setCountry: (country: Country) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  formatCurrency: (amount: number) => string;
  formatCurrencyParts: (amount: number) => { symbol: string; integer: string; cents: string };
  currentCountry: CountryConfig;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>("pt");
  const [currency, setCurrencyState] = useState<Currency>("BRL");
  const [country, setCountryState] = useState<Country>("BR");

  useEffect(() => {
    const savedLang = localStorage.getItem("language") as Language;
    const savedCurr = localStorage.getItem("currency") as Currency;
    const savedCountry = localStorage.getItem("country") as Country;

    if (savedLang) setLanguageState(savedLang);
    if (savedCurr) setCurrencyState(savedCurr);
    if (savedCountry) setCountryState(savedCountry);

    const loadSettings = async () => {
      const { data } = await supabase.from("settings").select("*");
      if (data) {
        const langSetting = data.find((s) => s.key === "language")?.value;
        const currSetting = data.find((s) => s.key === "currency")?.value;
        const countrySetting = data.find((s) => s.key === "country")?.value;

        if (langSetting) {
          setLanguageState(langSetting as Language);
          localStorage.setItem("language", langSetting);
        }
        if (currSetting) {
          setCurrencyState(currSetting as Currency);
          localStorage.setItem("currency", currSetting);
        }
        if (countrySetting) {
          setCountryState(countrySetting as Country);
          localStorage.setItem("country", countrySetting);
        }
      }
    };
    loadSettings();
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("language", lang);
  };

  const setCurrency = (curr: Currency) => {
    setCurrencyState(curr);
    localStorage.setItem("currency", curr);
  };

  const setCountry = (c: Country) => {
    setCountryState(c);
    localStorage.setItem("country", c);
    const countryData = countries.find((item) => item.code === c);
    if (countryData) {
      setLanguage(countryData.language);
      setCurrency(countryData.currency);
    }
  };

  const currentCountry = useMemo(() => {
    return countries.find((c) => c.code === country) || countries[2]; // Default to BR
  }, [country]);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let translation = translations[language][key] || key;
      if (params) {
        Object.entries(params).forEach(([key, value]) => {
          translation = translation.replace(`{${key}}`, String(value));
        });
      }
      return translation;
    },
    [language]
  );

  const formatCurrency = useCallback(
    (amount: number) => {
      const config = currencyConfig[currency];
      return new Intl.NumberFormat(config.locale, {
        style: "currency",
        currency: config.code,
      }).format(amount);
    },
    [currency]
  );

  const formatCurrencyParts = useCallback(
    (amount: number) => {
      const config = currencyConfig[currency];
      const formatter = new Intl.NumberFormat(config.locale, {
        style: "currency",
        currency: config.code,
      });

      const parts = formatter.formatToParts(amount);
      const symbol = parts.find((p) => p.type === "currency")?.value || "";
      const integer = parts
        .filter((p) => ["integer", "group"].includes(p.type))
        .map((p) => p.value)
        .join("");
      const cents = parts.find((p) => p.type === "fraction")?.value || "00";

      return { symbol, integer, cents };
    },
    [currency]
  );

  return (
    <I18nContext.Provider
      value={{
        language,
        currency,
        country,
        setLanguage,
        setCurrency,
        setCountry,
        t,
        formatCurrency,
        formatCurrencyParts,
        currentCountry,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (context === undefined) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
};
